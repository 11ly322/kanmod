function normalizeTag(tag) {
  return String(tag || '').trim().toLowerCase();
}

export function translateTag(tag) {
  const key = normalizeTag(tag);
  return TAGS[key] || String(tag || '');
}

export function tagTranslations() {
  return { ...TAGS };
}

export function tagSearchTerms(tag) {
  const key = normalizeTag(tag);
  const zh = TAGS[key];
  return zh ? [key, zh] : [key];
}

export default TAGS;
